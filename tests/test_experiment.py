from __future__ import annotations

from wt4.experiment import 实验输入


def test_相同规范输入生成稳定且顺序无关的实验身份() -> None:
    左 = 实验输入(
        策略实现提交="abc123",
        二进制哈希="bin",
        参数={"风险": 2.7, "周期": "M5"},
        数据指纹="ticks",
        成本快照="cost",
        合约规格="contract",
        mt5版本="5.0",
        建模方式=4,
        起始日="2024.01.01",
        结束日="2024.12.31",
        分区="开发",
    )
    右 = 实验输入(
        策略实现提交="abc123",
        二进制哈希="bin",
        参数={"周期": "M5", "风险": 2.7},
        数据指纹="ticks",
        成本快照="cost",
        合约规格="contract",
        mt5版本="5.0",
        建模方式=4,
        起始日="2024.01.01",
        结束日="2024.12.31",
        分区="开发",
    )

    assert 左.身份 == 右.身份
    assert len(左.身份) == 64
